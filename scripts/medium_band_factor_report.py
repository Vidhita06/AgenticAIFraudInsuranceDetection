"""How many medium-band validation claims have a concrete factor, and is their fraud rate
higher than for those without? Checks the medium-band guardrail rule against data.

    python scripts/medium_band_factor_report.py          # ~10 min on CPU (SHAP + retrieval per claim)

Writes docs/report/03b_medium_band_factors.md and docs/report/tables/03b_medium_band_factors.csv.
Factor definitions are the agent's own (src/agent/evidence.py: reason_codes and
concrete_factor_codes), with simulated reference data off and on. Labels are used only to
report fraud rates (evaluation), never by the agent.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from src.agent.evidence import concrete_factor_codes, find_conflicts, reason_codes  # noqa: E402
from src.config import path_for  # noqa: E402
from src.ml.evaluate import wilson_ci  # noqa: E402
from src.ml.predict import load_artifacts, predict_proba, risk_band  # noqa: E402
from src.tools import explain_claim, find_similar_claims, score_claim, verify_policy  # noqa: E402

FACTORS = ["RED_FLAGS_PRESENT", "POLICY_CONDITION_FAILED", "SIMILAR_CLAIMS_ELEVATED_FRAUD", "STRONG_SHAP_DRIVER",
           "CONFLICTING_EVIDENCE"]


def rate(k: int, n: int) -> str:
    if not n:
        return "–"
    lo, hi = wilson_ci(k, n)
    return f"{k}/{n} = {k / n:.1%} [{lo:.1%}, {hi:.1%}]"


def main() -> None:
    v = pd.read_csv(path_for("real_validation"))
    art = load_artifacts()
    v["band"] = [risk_band(p, art.bands) for p in predict_proba(v.drop(columns=["FraudFound_P"]), art)]
    bands = v.groupby("band").FraudFound_P.agg(["sum", "count"]).reindex(["low", "medium", "high"])
    has_sim_db = __import__("src.simulated.db", fromlist=["db_path"]).db_path().exists()
    rows = []
    for r in v[v.band == "medium"].to_dict("records"):
        label = r.pop("FraudFound_P")
        r.pop("band")
        tr = {"fraud_score": score_claim(r), "similar_claims": find_similar_claims(r, 5)}
        tr["shap_explanation"] = explain_claim(r, 5, fraud_score=tr["fraud_score"])
        row = {"policy_number": r["PolicyNumber"], "label": label}
        for mode in (("off", "on") if has_sim_db else ("off",)):
            t = {**tr, "policy_verification": verify_policy(r, simulated=mode == "on")}
            codes = set(reason_codes("FLAG_FOR_INVESTIGATION", {"conflicts": find_conflicts(t)}, t))
            for f in FACTORS:
                row[f"{f} ({mode})"] = f in codes
            row[f"any concrete factor ({mode})"] = bool(codes & concrete_factor_codes())
        rows.append(row)
    d = pd.DataFrame(rows)
    table = []
    for col in [c for c in d.columns if c.endswith(")")]:
        w, wo = d[d[col]], d[~d[col]]
        table.append({"factor": col, "claims with": len(w), "share": f"{len(w) / len(d):.1%}",
                      "fraud rate with [95% CI]": rate(int(w.label.sum()), len(w)),
                      "fraud rate without [95% CI]": rate(int(wo.label.sum()), len(wo))})
    t = pd.DataFrame(table)
    t.to_csv(ROOT / "docs" / "report" / "tables" / "03b_medium_band_factors.csv", index=False)
    md = ["# Medium-band claims: concrete factors vs fraud rate (real validation)", "",
          "_Generated by `scripts/medium_band_factor_report.py`. Factor definitions are the agent's own "
          "reason codes (`src/agent/evidence.py`)._", "",
          "## Fraud rate by risk band", "",
          "| band | claims | fraud rate [95% CI] |", "|---|---|---|"]
    md += [f"| {b} | {int(n)} | {rate(int(k), int(n))} |" for b, (k, n) in bands.iterrows()]
    md += ["", f"## Medium band ({len(d)} claims, {int(d.label.sum())} frauds)", "",
           "| factor | claims with | share | fraud rate with [95% CI] | fraud rate without [95% CI] |",
           "|---|---|---|---|---|"]
    md += [f"| {x['factor']} | {x['claims with']} | {x['share']} | {x['fraud rate with [95% CI]']} | "
           f"{x['fraud rate without [95% CI]']} |" for x in table]
    any_off = d["any concrete factor (off)"]
    k1, n1, k0, n0 = int(d.label[any_off].sum()), int(any_off.sum()), int(d.label[~any_off].sum()), int((~any_off).sum())
    lo1, hi1 = wilson_ci(k1, n1) if n1 else (0, 0)
    lo0, hi0 = wilson_ci(k0, n0) if n0 else (0, 0)
    verdict = ("higher" if n1 and n0 and lo1 > hi0 else "not higher" if n1 and n0 and k1 / n1 <= k0 / n0
               else "not clearly different")
    md += ["", "## Reading", "",
           f"- Medium-band claims with a concrete factor (simulated data off): fraud rate {k1}/{n1}"
           f"{f' = {k1 / n1:.1%}' if n1 else ''}; without: {k0}/{n0}{f' = {k0 / n0:.1%}' if n0 else ''}. "
           f"The rate with a factor is **{verdict}** (95% intervals "
           f"[{lo1:.1%}, {hi1:.1%}] vs [{lo0:.1%}, {hi0:.1%}]).",
           "- The red flags and the red-flag score are model features, so once a claim's score falls in the "
           "medium band they carry little extra information; every medium-band claim has at least one "
           "red flag and a positive red-flag-score SHAP contribution.",
           "- So the factors are a requirement for an *explainable* flag (an adjuster can check them), "
           "not a proven way to find more fraud inside the medium band. With "
           f"{int(bands.loc['medium', 'sum'])} frauds the intervals are wide; the live evaluation reports "
           "FRAUD_RISK flags by risk band with their fraud rate, which shows whether the agent's medium-band flags add value."]
    out = ROOT / "docs" / "report" / "03b_medium_band_factors.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
